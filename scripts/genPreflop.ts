/**
 * Generates src/bots/preflopTable.ts: every starting hand class ranked by strength,
 * blending heads-up equity with 4-way equity (so suited/connected hands get credit
 * for multiway playability). Run: npx tsx scripts/genPreflop.ts
 */
import { writeFileSync } from 'node:fs';
import { makeCard, RANKS } from '../src/engine/cards';
import { evaluate } from '../src/engine/evaluator';

const SIMS = Number(process.env.SIMS ?? 30000);

function classes() {
  const out: { key: string; a: number; b: number; combos: number }[] = [];
  for (let i = 12; i >= 0; i--)
    for (let j = i; j >= 0; j--) {
      if (i === j) out.push({ key: RANKS[i] + RANKS[j], a: makeCard(i, 0), b: makeCard(j, 1), combos: 6 });
      else {
        out.push({ key: RANKS[i] + RANKS[j] + 's', a: makeCard(i, 0), b: makeCard(j, 0), combos: 4 });
        out.push({ key: RANKS[i] + RANKS[j] + 'o', a: makeCard(i, 0), b: makeCard(j, 1), combos: 12 });
      }
    }
  return out;
}

function equity(a: number, b: number, opps: number, sims: number): number {
  const base = Array.from({ length: 52 }, (_, i) => i).filter((c) => c !== a && c !== b);
  let won = 0;
  const deck = base.slice();
  for (let s = 0; s < sims; s++) {
    // partial shuffle for 5 + 2*opps cards
    const need = 5 + 2 * opps;
    for (let i = 0; i < need; i++) {
      const j = i + Math.floor(Math.random() * (deck.length - i));
      [deck[i], deck[j]] = [deck[j], deck[i]];
    }
    const board = deck.slice(0, 5);
    const hero = evaluate([a, b, ...board]);
    let best = 0;
    let ties = 1;
    let heroBest = true;
    for (let o = 0; o < opps; o++) {
      const v = evaluate([deck[5 + 2 * o], deck[6 + 2 * o], ...board]);
      if (v > hero) { heroBest = false; break; }
      if (v === hero) ties++;
      best = Math.max(best, v);
    }
    if (heroBest) won += 1 / ties;
  }
  return won / sims;
}

const rows = classes().map((c) => {
  const hu = equity(c.a, c.b, 1, SIMS);
  const mw = equity(c.a, c.b, 3, SIMS);
  return { ...c, hu, mw };
});

const mean = (xs: number[]) => xs.reduce((s, x) => s + x, 0) / xs.length;
const sd = (xs: number[]) => Math.sqrt(mean(xs.map((x) => (x - mean(xs)) ** 2)));
const huM = mean(rows.map((r) => r.hu)), huS = sd(rows.map((r) => r.hu));
const mwM = mean(rows.map((r) => r.mw)), mwS = sd(rows.map((r) => r.mw));
// Raw all-in equity ignores implied odds and playability, which is why real ranges
// play small pairs and suited connectors far more than equity alone suggests.
function playability(key: string): number {
  const hi = RANKS.indexOf(key[0]);
  const lo = RANKS.indexOf(key[1]);
  if (hi === lo) return 0.55 + (lo < 6 ? 0.25 : 0); // set-mining value
  const suited = key[2] === 's';
  const gap = hi - lo - 1;
  const wheelAce = hi === 12 && lo <= 3;
  let b = 0;
  if (suited) b += 0.3;
  if (gap === 0) b += 0.3;
  else if (gap === 1) b += 0.15;
  else if (gap === 2) b += 0.05;
  if (suited && wheelAce) b += 0.1;
  if (!suited && gap >= 3 && hi < 12) b -= 0.25; // disconnected offsuit junk
  if (!suited && hi === 12 && lo < 7) b -= 0.15; // weak offsuit aces are traps
  return b;
}

const scored = rows
  .map((r) => ({
    ...r,
    score: 0.55 * ((r.hu - huM) / huS) + 0.45 * ((r.mw - mwM) / mwS) + playability(r.key),
  }))
  .sort((x, y) => y.score - x.score);

let cum = 0;
const table: Record<string, [number, number]> = {};
for (const r of scored) {
  const start = cum;
  cum += r.combos;
  // percentile = midpoint of the hand's slice of the 1326 combos (0 = best)
  table[r.key] = [Number(((start + r.combos / 2) / 1326).toFixed(4)), Number(r.hu.toFixed(3))];
}

const src = `// Generated by scripts/genPreflop.ts — do not edit by hand.
// key -> [percentile (0 = best, 1 = worst), heads-up equity vs a random hand]
export const PREFLOP: Record<string, [number, number]> = ${JSON.stringify(table)};
export const PREFLOP_ORDER: string[] = ${JSON.stringify(scored.map((r) => r.key))};
`;
writeFileSync(new URL('../src/bots/preflopTable.ts', import.meta.url), src);
for (const pct of [0.08, 0.15, 0.25, 0.45]) {
  const inRange = scored.filter((r) => table[r.key][0] <= pct).map((r) => r.key);
  console.log(`top ${pct * 100}% (${inRange.length} classes):`, inRange.join(' '));
}
